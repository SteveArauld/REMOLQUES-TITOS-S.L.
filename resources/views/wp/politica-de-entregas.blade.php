<p class="wp-block-paragraph">En Remolques Titos, nos esforzamos por ofrecerte una experiencia de envío rápida, confiable y conveniente.</p>



<ol class="wp-block-list">
<li>Tiempo de Procesamiento de Pedidos:</li>
</ol>



<p class="wp-block-paragraph">Los pedidos realizados antes de las 18:00 horas se procesarán el mismo día, de lunes a viernes.</p>



<ol class="wp-block-list" start="2">
<li>Tiempo de Envío:</li>
</ol>



<p class="wp-block-paragraph">Una vez procesados, los pedidos serán enviados en un plazo de 1 a 2 días hábiles.</p>



<p class="wp-block-paragraph">El tiempo de entrega estándar es de 3 a 10 días hábiles.</p>



<ul class="wp-block-list">
<li>3 a 5 días para artículos ligeros.</li>



<li>3 a 10 días para artículos pesados como tractores y otras máquinas grandes.</li>
</ul>



<p class="wp-block-paragraph">Condiciones de Envío:<br>Remolques Titos realiza sus envíos con las mejores agencias de transporte: ASM, GLS o Correos Express, según la zona geográfica y las características del envío, desde España.</p>



<p class="wp-block-paragraph">ENVÍO A NORUEGA, SUIZA Y REINO UNIDO (INGLATERRA, GALES Y ESCOCIA): Los gastos de transporte y aduanas están incluidos en el total del pedido. El cliente deberá pagar los impuestos de importación en su país al recibir su pedido.</p>



<ol class="wp-block-list" start="4">
<li>Días de Entrega:</li>
</ol>



<p class="wp-block-paragraph">Las entregas se realizan de lunes a viernes.<br>No se realizan entregas los fines de semana.</p>



<ol class="wp-block-list" start="5">
<li>Costos de Envío:</li>
</ol>



<p class="wp-block-paragraph">Los costos de envío ya están incluidos en los artículos, por lo que la entrega es gratuita.</p>



<ol class="wp-block-list" start="6">
<li>Transportistas:</li>
</ol>



<p class="wp-block-paragraph">Hemos seleccionado transportistas de confianza para garantizar la seguridad y rapidez de sus entregas: ASM, GLS o Correos Express.</p>



<ol class="wp-block-list" start="7">
<li>Seguimiento de Pedido:</li>
</ol>



<p class="wp-block-paragraph">Recibirás un número de seguimiento una vez que tu pedido haya sido enviado, lo que te permitirá seguir el estado de tu entrega en tiempo real.</p>



<ol class="wp-block-list" start="8">
<li>Reembolsos, Devoluciones e Intercambios:</li>
</ol>



<p class="wp-block-paragraph">Aceptamos devoluciones hasta 14 días después de la entrega, si el artículo no ha sido usado y está en su estado original, y te reembolsaremos el total del pedido menos los costos de envío de la devolución.</p>



<p class="wp-block-paragraph">En caso de que tu pedido llegue dañado, por favor envíanos un correo electrónico lo antes posible a contacto@remolquestitos.es con tu número de pedido y una foto del artículo. Trataremos estos casos de manera individual, pero haremos todo lo posible por encontrar una solución satisfactoria.</p>



<p class="wp-block-paragraph">Si tienes alguna otra pregunta, no dudes en contactarnos a contacto@remolquestitos.es.</p>
			
