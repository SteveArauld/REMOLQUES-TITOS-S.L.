<p class="wp-block-paragraph"><strong>Devoluciones </strong></p>



<p class="wp-block-paragraph">Puede devolver su pedido/artículo(s) para obtener un reembolso en un plazo de 14 días a partir de la recepción de su pedido. Tenga en cuenta que las devoluciones son responsabilidad del cliente hasta que lleguen a nuestro depósito. Por lo tanto, recomendamos que utilice un servicio con rastreo. Conserve siempre evidencia del comprobante de envío.</p>



<p class="wp-block-paragraph"><br>Tenga en cuenta que:</p>



<p class="wp-block-paragraph"><br>&#8211; Los costos y riesgos asociados con la devolución de un artículo o artículos están totalmente a cargo del cliente.<br>&#8211; Los costos de impuestos de importación relacionados a su envío serán deducidos de su reembolso.<br>&#8211; Actualmente aceptamos solamente devoluciones de personas físicas y no de empresas/comerciantes.</p>



<p class="wp-block-paragraph">Los artículos deben ser devueltos en la misma condición en la que fueron recibidos y en su envoltorio original. Los artículos se inspeccionarán al ser devueltos. Si consideramos a los artículos invendibles, no se reembolsarán ni devolverán.<br>En el caso poco probable de que reciba un producto fallado o dañado, contáctenos de forma inmediata a contacto@remolquestitos.com antes de devolver el artículo o artículos y lo ayudaremos con su consulta.</p>



<p class="wp-block-paragraph"><br>Procedimiento de devoluciones</p>



<p class="wp-block-paragraph"><br>1. Infórmenos sobre su devolución a contacto@remolquestitos.com<br>2. Por favor adjunte toda la documentación en su envío. Los clientes internacionales/de países fuera de la UE deben colocar un comprobante de empaque y factura de su pedido en un sobre de plástico y adherirlo al paquete.<br>3. Asegúrese de que el artículo o artículos estén empacados en su envoltorio original<br>4. Lleve su paquete a la oficina postal más cercana. La dirección de envío es: Avenida Los Emigrantes, s/n<br>18560 Guadahortuna (Granada), Andalucía, España.</p>



<p class="wp-block-paragraph"><strong>Reembolsos</strong></p>



<p class="wp-block-paragraph">Los reembolsos se emiten únicamente al método de pago original utilizado.<br>Si no está satisfecho con el artículo o artículos pedidos, puede recibir un reembolso total por el artículo o artículos dentro de los 14 días siguientes a la recepción de su pedido en artículos en su envoltorio original.<br>Los reembolsos pueden tardar de 10 a 15 días en procesar una vez que el artículo o artículos haya llegado a nuestro establecimiento de devoluciones.</p>



<p class="wp-block-paragraph"><br><strong>Pagos con tarjeta de débito/crédito:</strong><br>Tenga en cuenta que los reembolsos a tarjetas de débito/crédito suelen reflejarse dentro de los 3-5 días hábiles.</p>



<p class="wp-block-paragraph"><br><strong>Pago mediante transferencia bancaria or <strong>Contrarrembolso</strong>:</strong><br>Si ha realizado una transferencia bancaria para realizar el pago, contáctenos a contacto@remolquestitos.com y proporcione sus detalles de cuenta bancaria: beneficiario, número de IBAN y código SWIFT. Tenga en cuenta que los reembolsos mediante transferencia bancaria suelen reflejarse dentro de los 5-7 días hábiles.</p>
			
